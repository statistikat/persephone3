# summary.persephone and the helpers it needs. The numbers come from the
# shared getters of the package, getRegressors() and
# generate_diagnostics_table(), so nothing is computed twice; only the
# derived Sunday regressor and the ARIMA parameter table are read from the
# estimation output directly.

#' Summary of a Seasonal Adjustment
#'
#' Prints a summary of a run of a single series: the frequency, span and
#' length of the series, the model definition of the regression ARIMA model
#' (ARIMA specification, transformation, leap year and trading day effects,
#' Easter effect, number of outliers and the result of the combined
#' seasonality test), the estimates of the ARIMA
#' parameters, the regression coefficients with their standard errors, t
#' values and p-values in one table per group (outliers, trading day
#' regressors, mean and leap year, user-defined regressors), the joint F
#' test of the trading day regressors, the decomposition filters and, at the
#' end, the summary indicators Q and Q-M2 of the X-11 M-statistics and the
#' overall quality indicator.
#'
#' @details
#'
#' The tables reuse the output of [getRegressors()] and the diagnostic row
#' of [diagnosticsTable()], so the summary is consistent with
#' `obj$getRegressors()` and `diagnosticsTable(obj)`.
#'
#' In the trading day table the regressors are labelled with their names (the
#' column names of the user-defined regressors passed to the `user` argument
#' of [perX13()] or [perTramo()]; the generic group names of the calendar
#' regressors are shown as the days Monday to Saturday). When the trading day
#' regression consists of the six day regressors, the effect of the reference
#' day Sunday is derived from the six effects and shown as an additional row
#' "Sunday (derived)": minus their sum for regressors given as contrasts
#' against Sunday, as generated by the trading day modules of JDemetra+ and
#' by [genTd()], minus one seventh of their sum for regressors centered with
#' respect to the mean day (the two cases are distinguished automatically
#' when the design matrix of the estimation is available).
#'
#' The leap year effect counts as included ("Leap year: Yes") if a dedicated
#' leap year regressor is part of the regression or if the series is log
#' transformed with a leap year or length-of-month adjustment
#' (`transform.adjust = "leapyear"` or `"lom"`). A user-defined regressor
#' given to the `user` argument of [perX13()] or [perTramo()] and named like
#' a leap year is such a regressor; the further user-defined regressors are
#' shown in a table "User-defined regressors".
#'
#' The "Identifiable seasonality" row shows the result of JDemetra+'s
#' combined seasonality test (the same source as the `seasonality` column of
#' [diagnosticsTable()]): typically "Yes" when the test detects identifiable
#' seasonality and "No" otherwise; other reported values (such as
#' "Uncertain" or "Undefined") are shown unchanged, a missing result as
#' "Not available".
#'
#' Q and Q-M2 are not single M-statistics but composite quality indicators
#' built from the X-11 M-statistics M1 to M11: Q is their weighted mean, Q-M2
#' the same composite computed without M2. The individual M-statistics range
#' from 0 to 3 and are accepted below 1, so Q and Q-M2 indicate a
#' satisfactory quality of the seasonal adjustment when they are below 1.
#' See the
#' [JDemetra+ documentation](https://jdemetradocumentation.github.io/JDemetra-documentation/pages/reference-manual/sa-output-X13.html).
#'
#' @param object a `persephone` object of a single series (created with
#'   [perX13()] or [perTramo()]) for which `run()` has been called.
#' @param ... currently ignored.
#'
#' @return `object`, invisibly.
#'
#' @examples
#' \dontrun{
#' data(AirPassengers, package = "datasets")
#' obj <- perX13(AirPassengers, "rsa3")
#' obj$run()
#' summary(obj)
#' }
#'
#' @export
summary.persephone <- function(object, ...) {
  if (!inherits(object, "persephoneSingle")) {
    stop("summary() is only available for single series objects ",
         "(perX13() and perTramo()).", call. = FALSE)
  }
  if (is.null(object$output)) {
    stop("No results from run available.\n", call. = FALSE)
  }
  if (identical(object$result$backend, "native")) {
    d <- generate_diagnostics_table(object)
    engine <- if (object$method == "tramoseats") "TRAMO / SEATS" else "X-13 / X-11"
    cat("Native", engine, object$result$provenance$mode_effective, "\n")
    cat("Observations", length(object$ts), "| Log transform", diagnostic_format(d$logTransform),
        "| Outliers", d$nOutliers, "\n")
    cat("ARIMA", diagnostic_format(d$arimaMdl), "\n")
    coefficients <- unlist(object$result$model$coefficients)
    if (length(coefficients)) print(coefficients)
    reg <- getRegressors(object)
    if (!is.null(reg)) print(reg)
    cat("Coefficient standard errors and JDemetra quality indicators are unavailable.\n")
    return(invisible(object))
  }
  ts <- object$ts
  ud <- object$output$user_defined

  # one call each: the regression coefficient table and the diagnostic row
  reg <- getRegressors(object)
  if (is.null(reg)) {
    reg <- data.frame(
      name = character(0), type = character(0), value = numeric(0),
      stde = numeric(0), t = numeric(0), pvalue = numeric(0),
      stringsAsFactors = FALSE
    )
  }
  drow <- generate_diagnostics_table(object)

  # ---- header ----
  cat("Frequency:", stats::frequency(ts), "  ",
      "Observations:", length(ts), "  ",
      "Span:", paste(sumPeriod(ts, stats::start(ts)), "-",
                     sumPeriod(ts, stats::end(ts))), "\n\n")

  # ---- model definition ----
  n_td <- sum(reg$type == "TD")
  # user-defined regressors of the regression model (the `user` argument of
  # perX13()/perTramo()); a leap year regressor among them is counted as leap
  # year, not here
  user_row <- isUserRow(reg)
  n_user <- sum(user_row)
  cat("-- Model definition ", strrep("-", 42), "\n", sep = "")
  cat("ARIMA model:     ", drow$arimaMdl, "\n")
  cat("Transformation:  ", if (isTRUE(drow$logTransform)) "Log" else "None", "\n")
  cat("Leap year:       ", if (hasLeapYear(object)) "Yes" else "None", "\n")
  cat("Trading day:     ",
      paste0(n_td, if (n_td == 1) " regressor" else " regressors"), "\n")
  cat("Easter effect:   ", if ("EASTER" %in% reg$type) "Yes" else "None", "\n")
  cat("Outliers:        ", drow$nOutliers, "\n")
  if (n_user > 0) {
    cat("User regressors: ", n_user, "\n")
  }
  # result of JDemetra+'s combined seasonality test, the same source as the
  # `seasonality` column of diagnosticsTable()
  cat("Identifiable seasonality: ",
      if (is.null(drow$seasonality) || is.na(drow$seasonality)) {
        "Not available"
      } else {
        as.character(drow$seasonality)
      }, "\n")
  cat("\n")

  # ---- coefficient tables ----
  sumPrintCoef(
    sumArimaTable(object),
    paste("ARIMA parameters", drow$arimaMdl)
  )
  sumPrintCoef(
    sumCoefFromReg(reg, reg$type == "outlier"),
    "Outliers"
  )
  td_sel <- reg$type == "TD"
  tdTab <- sumCoefFromReg(reg, td_sel, sumTdLabels(object, sum(td_sel)))
  if (!is.null(tdTab) && nrow(tdTab) == 6 &&
      !any(grepl("^sun", tolower(rownames(tdTab))))) {
    # six day regressors (Monday to Saturday): the effect of the reference
    # day Sunday is derived from them and added as a further row
    sunday <- sumTdSunday(object)
    if (!is.null(sunday)) {
      tdTab <- rbind(tdTab, sunday)
    }
  }
  sumPrintCoef(tdTab, "Trading day regressors")
  leap_sel <- reg$type %in% c("MEAN", "LP") | isUserLeapRow(reg)
  leap_lab <- ifelse(
    reg$type == "MEAN", "const",
    ifelse(reg$type == "LP" | isUserLeapRow(reg), "leap year", reg$name)
  )
  sumPrintCoef(
    sumCoefFromReg(reg, leap_sel, leap_lab[leap_sel]),
    "Mean / Leap year"
  )
  sumPrintCoef(
    sumCoefFromReg(reg, user_row),
    "User-defined regressors"
  )

  # ---- joint F tests (trading days, from the attribute of getRegressors) ----
  ft <- attr(reg, "ftests")
  if (!is.null(ft) && nrow(ft) > 0) {
    cat("-- Joint F tests ", strrep("-", 44), "\n", sep = "")
    printFTests(ft)
    cat("\n")
  }

  # ---- SA decomposition ----
  cat("-- SA decomposition ", strrep("-", 41), "\n", sep = "")
  cat("Seasonal adjustment: ", tolower(as.character(ud$mode)), "\n")
  if (inherits(object$output$decomposition, "JD3X11")) {
    dec <- object$output$decomposition
    cat("Final MA filter:     ", sumFilterName(dec$final_seasonal), "\n")
    hend <- dec$final_henderson
    if (!is.null(hend) && !is.na(hend)) {
      cat("Final trend-cycle:   ",
          paste0(hend, "-term Henderson filter"), "\n")
    }
  } else {
    cat("Decomposition:       SEATS (no X-11 filters)\n")
  }

  # ---- quality: M-statistics preferably from the user_defined nodes
  # (reported by the run), else from the diagnostic row (output$mstats,
  # the source of diagnosticsTable()); rounded to its two decimals ----
  ud_q <- ud$`m-statistics.q`
  ud_q2 <- ud$`m-statistics.q-m2`
  qv <- if (!is.null(ud_q) && length(ud_q) == 1 && !is.na(ud_q)) {
    round(as.numeric(ud_q), 2)
  } else {
    drow$Q
  }
  q2v <- if (!is.null(ud_q2) && length(ud_q2) == 1 && !is.na(ud_q2)) {
    round(as.numeric(ud_q2), 2)
  } else {
    drow$Q2
  }
  hasQ <- !is.null(qv) && !is.na(qv)
  hasTotalQ <- !is.null(drow$TotalQ) && !is.na(drow$TotalQ)
  if (hasQ || hasTotalQ) {
    cat("\n-- Quality ", strrep("-", 54), "\n", sep = "")
    if (hasQ) {
      cat("M-statistics summary:",
          paste0("Q = ", sumNum(qv),
                 if (!is.null(q2v) && !is.na(q2v))
                   paste0("   Q-M2 = ", sumNum(q2v))), "\n")
    }
    if (hasTotalQ) {
      cat("Total quality:       ", as.character(drow$TotalQ), "\n")
    }
  }
  invisible(object)
}

