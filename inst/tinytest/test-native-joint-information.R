local({
  setup <- getFromNamespace("native_arma_objective_setup","persephone3")
  optimize <- getFromNamespace("native_arma_optimize","persephone3")
  information <- getFromNamespace("native_arma_information","persephone3")
  regression <- getFromNamespace("native_regression_information","persephone3")
  joint <- function(objective,coordinates=objective$parameters$initial_coordinates,...) {
    regression(objective,coordinates,method="joint_profile_ml",...)
  }
  source("fixtures/native/arma-fit-cases.R",local=TRUE)
  source("fixtures/native/arma-residual-oracle.R",local=TRUE)
  source("fixtures/native/joint-information-oracle.R",local=TRUE)
  relative <- function(a,b) sqrt(sum((a-b)^2)/sum(b^2))
  cases <- arma_fit_cases()
  for(ca in cases) {
    context <- do.call(setup,ca$arguments)
    fit <- optimize(context,control=list(max_iterations=200L,max_evaluations=4000L))
    original <- serialize(context,NULL)
    result <- joint(context,fit$coordinates)
    expect_identical(result$status,"available",info=ca$id)
    expect_true(result$available && result$propagates_ARMA_uncertainty)
    expect_identical(result$method,"joint_profile_ml")
    expect_identical(result$arma_method,"profile_ml")
    expect_identical(result$arma_covariance_mode,"accurate")
    expect_identical(result$scale_convention,"profiled_ML_Q_over_n_finite")
    expect_identical(result$sensitivity_status,"available")
    expect_identical(result$free_regression,2L)
    expect_identical(result$free_columns,c(1L,3L))
    expect_identical(result$free_ARMA,as.integer(sum(is.na(unlist(ca$specification)))))
    basis <- arma_residual_basis(ca,fit$final$parameters$coefficients)
    C <- basis$regression_covariance_unit*sum(basis$residuals^2)/basis$finite
    expect_equal(unname(result$conditional_ml_covariance),C,tolerance=1e-7)
    expect_equal(result$residual_variance,sum(basis$residuals^2)/basis$finite,tolerance=1e-10)
    expect_equal(unname(result$coefficients),basis$coefficients,tolerance=1e-9)
    oracle <- joint_information_oracle(ca,fit$final$parameters$coefficients,basis$coefficients,
      sqrt(diag(C)),sqrt(diag(result$arma_covariance)))
    # Budgets declared before qualification: each physical GLS derivative is
    # within 2e-7*(1+abs(B)); covariance in standardized coordinates within 2e-5.
    expect_true(all(abs(result$sensitivity-oracle$sensitivity)<2e-7*(1+abs(oracle$sensitivity))),info=ca$id)
    scaled <- result$joint_covariance/outer(oracle$scale,oracle$scale)
    expect_true(relative(scaled,oracle$scaled_covariance)<2e-5,info=ca$id)
    expect_true(max(abs(scaled%*%oracle$scaled_hessian-diag(nrow(scaled))))<2e-5,info=ca$id)
    expect_equal(unname(result$covariance),unname(C+result$sensitivity%*%result$arma_covariance%*%t(result$sensitivity)),tolerance=1e-10)
    expect_equal(unname(result$cross_covariance),unname(result$sensitivity%*%result$arma_covariance),tolerance=1e-10)
    expect_true(min(eigen(result$covariance-result$conditional_ml_covariance,symmetric=TRUE,only.values=TRUE)$values)>-1e-12)
    expect_identical(result$joint_covariance,t(result$joint_covariance))
    expect_identical(rownames(result$cross_covariance),names(result$coefficients))
    expect_identical(colnames(result$cross_covariance),names(result$arma_coefficients))
    expect_identical(rownames(result$joint_covariance),c(paste0("regression.",names(result$coefficients)),paste0("ARMA.",names(result$arma_coefficients))))
    expect_equal(result$standard_errors,sqrt(diag(result$covariance)),tolerance=0)
    expect_true(result$evaluations==result$arma_information$evaluations+result$sensitivity_evaluations)
    expect_true(all(is.finite(result$sensitivity_error)) && all(result$sensitivity_error>=0))
    expect_identical(serialize(context,NULL),original)
    expect_identical(unserialize(serialize(result,NULL)),result)
  }
  ca <- cases[["4-ar-complete-none"]];context <- do.call(setup,ca$arguments)
  fit <- optimize(context);base <- joint(context,fit$coordinates)
  primary <- information(context,fit$coordinates)
  for(budget in c(1L,primary$evaluations,primary$evaluations+1L,base$evaluations-1L)) {
    limited <- joint(context,fit$coordinates,control=list(max_evaluations=budget))
    expect_false(limited$available)
    expect_true(is.null(limited$covariance) && is.null(limited$joint_covariance) && is.null(limited$cross_covariance))
    expect_true(all(is.na(limited$standard_errors)) && limited$evaluations<=budget)
    if(budget>=primary$evaluations) {
      expect_identical(limited$status,"evaluation_limit")
      expect_equal(limited$conditional_ml_covariance,base$conditional_ml_covariance,tolerance=0)
      expect_identical(limited$arma_information$status,"available")
    }
  }
  expect_true(joint(context,fit$coordinates,control=list(max_evaluations=base$evaluations))$available)
  for(scale in c(.001,7,100)) {
    args <- ca$arguments;args$series <- args$series*scale;args$regressors$fixed <- args$regressors$fixed*scale
    changed <- joint(do.call(setup,args),fit$coordinates)
    expect_identical(changed$status,"available")
    expect_true(relative(changed$covariance,base$covariance*scale^2)<1e-6)
    expect_true(relative(changed$cross_covariance,base$cross_covariance*scale)<1e-6)
    expect_true(relative(changed$sensitivity,base$sensitivity*scale)<1e-6)
  }
  args <- ca$arguments;args$regressors$x <- args$regressors$x*7
  changed <- joint(do.call(setup,args),fit$coordinates);change <- diag(c(1/7,1))
  expect_true(relative(changed$covariance,change%*%base$covariance%*%change)<1e-6)
  expect_true(relative(changed$cross_covariance,change%*%base$cross_covariance)<1e-6)
  args <- ca$arguments;args$series <- args$series+1000*head(args$regressors$x,length(args$series))
  changed <- joint(do.call(setup,args),fit$coordinates)
  expect_identical(changed$status,"available")
  expect_true(relative(changed$covariance,base$covariance)<1e-6)
  expect_true(relative(changed$sensitivity,base$sensitivity)<1e-6)
  for(point in list(context$parameters$initial_coordinates,1000)) {
    unavailable <- joint(context,point)
    expect_false(unavailable$available)
    expect_true(is.null(unavailable$joint_covariance) && all(is.na(unavailable$standard_errors)))
    expect_identical(names(unavailable$standard_errors),names(base$standard_errors))
    expect_identical(unavailable$free_ARMA,1L)
  }
  y <- ts(c(.2,.6,-.3,.1,-.7,-.3,.1,.7,.6,-.2,-.5,.3),frequency=4)
  white <- setup(y,include_mean=TRUE)
  fixed <- joint(white);conditional <- regression(white)
  expect_identical(fixed$sensitivity_status,"not_required")
  expect_identical(dim(fixed$cross_covariance),c(1L,0L))
  expect_equal(fixed$covariance,conditional$covariance*11/12,tolerance=1e-12)
  expect_equal(as.numeric(fixed$covariance),sum((y-mean(y))^2)/12^2,tolerance=1e-12)
  ar <- setup(y,ar=NA_real_);fitted <- optimize(ar);none <- joint(ar,fitted$coordinates)
  expect_true(none$available)
  expect_identical(dim(none$covariance),c(0L,0L))
  expect_identical(dim(none$cross_covariance),c(0L,1L))
  expect_equal(unname(none$joint_covariance),unname(none$arma_covariance),tolerance=1e-12)
  empty <- joint(setup(y,ar=.3))
  expect_identical(empty$status,"no_free_parameters")
  expect_identical(dim(empty$joint_covariance),c(0L,0L))
  expect_equal(length(empty$standard_errors),0)
  aliased <- joint(setup(y,ar=.3,regressors=list(x=y,x2=y)))
  expect_false(aliased$available)
  expect_true(all(is.na(aliased$standard_errors)) && is.null(aliased$joint_covariance))
  common <- joint(setup(y,ar=NA_real_,ma=NA_real_,initial=list(ar=.3,ma=-.3),include_mean=TRUE))
  expect_identical(common$arma_information_status,"structural_redundancy")
  expect_false(common$available)
  weak <- joint(context,fit$coordinates,control=list(weak_tolerance=.99))
  expect_identical(weak$status,"weak_joint_covariance")
  expect_true(is.null(weak$joint_covariance) && all(is.na(weak$standard_errors)))
  for(method in c("conditional_residual_df","tramo_residual","unknown")) {
    expect_error(joint(context,fit$coordinates,arma_method=method))
  }
  expect_error(joint(context,fit$coordinates,covariance="legacy"))
  expect_error(joint(context,fit$coordinates,legacy_state=list()))
  expect_error(joint(list(),numeric()))
  seed <- if(exists(".Random.seed",.GlobalEnv))get(".Random.seed",.GlobalEnv)else NULL
  set.seed(10101);noise <- rnorm(240)
  for(phi in c(.97,.995)) {
    persistent <- ts(as.numeric(filter(noise,phi,method="recursive")),frequency=4)
    context <- setup(persistent,ar=NA_real_,include_mean=TRUE)
    fit <- optimize(context,control=list(max_iterations=200L,max_evaluations=4000L))
    result <- joint(context,fit$coordinates)
    n <- length(persistent);p <- unname(result$arma_coefficients)
    derivative <- ((n-2)*(persistent[1L]+persistent[n])-2*sum(persistent[2:(n-1L)]))/(2+(n-2)*(1-p))^2
    expect_identical(result$status,"available")
    expect_equal(as.numeric(result$sensitivity),derivative,tolerance=1e-7)
    expect_true(all(is.finite(result$standard_errors)))
  }
  if(is.null(seed))rm(".Random.seed",envir=.GlobalEnv)else assign(".Random.seed",seed,.GlobalEnv)
  old <- Sys.getenv("PERSEPHONE_NUM_THREADS",unset=NA_character_)
  on.exit(if(is.na(old))Sys.unsetenv("PERSEPHONE_NUM_THREADS")else Sys.setenv(PERSEPHONE_NUM_THREADS=old),add=TRUE)
  # Dense monthly integrated whitening also exercises worker-capable channels.
  ca <- cases[["12-airline-gaps-log"]];context <- do.call(setup,ca$arguments);fit <- optimize(context)
  Sys.setenv(PERSEPHONE_NUM_THREADS=1);serial <- joint(context,fit$coordinates)
  Sys.setenv(PERSEPHONE_NUM_THREADS=2);threaded <- joint(context,fit$coordinates)
  expect_identical(serial$status,threaded$status)
  expect_equal(serial$joint_covariance,threaded$joint_covariance,tolerance=1e-10)
  expect_true(all(abs(serial$sensitivity-threaded$sensitivity) <= serial$sensitivity_error+threaded$sensitivity_error))
})
