local({
  setup <- getFromNamespace("native_arma_objective_setup","persephone3")
  optimize <- getFromNamespace("native_arma_optimize","persephone3")
  residuals <- getFromNamespace("native_arma_residuals","persephone3")
  information <- getFromNamespace("native_interpolation_information","persephone3")
  source("fixtures/native/arma-fit-cases.R",local=TRUE)
  source("fixtures/native/legacy-residual-cases.R",local=TRUE)
  source("fixtures/native/interpolation-oracle.R",local=TRUE)
  for(ca in arma_fit_cases()) {
    context <- do.call(setup,ca$arguments);before <- serialize(context,NULL)
    fit <- optimize(context,control=list(max_iterations=200L,max_evaluations=4000L))
    actual <- information(context,fit$coordinates)
    accurate <- residuals(context,fit$coordinates)
    target <- interpolation_oracle(context,fit$final$parameters$coefficients)
    expect_true(actual$available && actual$point_available,info=ca$id)
    expect_identical(actual$points_transformed,accurate$interpolation$points_transformed)
    expect_identical(actual$center,accurate$center)
    expect_equal(actual$points_transformed,target$points,tolerance=2e-8)
    expect_identical(actual$rows,target$rows)
    expect_identical(actual$source_rows,ca$rows[target$rows])
    expect_equal(unname(actual$covariance),target$covariance*target$Q/target$n,tolerance=2e-8,info=ca$id)
    expect_equal(unname(actual$known_regression_covariance),target$known*target$Q/target$n,tolerance=2e-8)
    expect_equal(unname(actual$regression_covariance),target$regression*target$Q/target$n,tolerance=2e-8)
    expect_equal(actual$covariance,actual$known_regression_covariance+actual$regression_covariance,tolerance=1e-12)
    expect_equal(actual$standard_errors,sqrt(diag(actual$covariance)),tolerance=1e-12,check.attributes=FALSE)
    expect_equal(as.numeric(actual$aligned_standard_errors[actual$rows]),actual$standard_errors,tolerance=0)
    expect_true(all(is.na(actual$aligned_standard_errors[-actual$rows])))
    expect_identical(tsp(actual$aligned_standard_errors),tsp(context$prepared$inputs$original))
    expect_identical(actual$unfilled_rows,accurate$interpolation$unfilled_rows)
    expect_false(actual$propagates_ARMA_uncertainty || actual$comparison_only)
    expect_identical(actual$standard_errors_scale,"transformed")
    expect_identical(serialize(context,NULL),before)
    expect_identical(unserialize(serialize(actual,NULL)),actual)
    df <- information(context,fit$coordinates,scale="residual_df")
    expect_identical(df$points_transformed,actual$points_transformed)
    expect_equal(df$covariance,actual$covariance*actual$effective_count/actual$residual_df,tolerance=1e-10)
    if(length(actual$rows)) {
      expect_identical(actual$status,"available")
      expect_equal(actual$scale_variance,actual$sum_squares/actual$effective_count,tolerance=1e-12)
      expect_equal(df$scale_variance,actual$sum_squares/actual$residual_df,tolerance=1e-12)
      expect_true(min(eigen(actual$covariance,symmetric=TRUE,only.values=TRUE)$values)>0)
      expect_true(min(eigen(actual$regression_covariance,symmetric=TRUE,only.values=TRUE)$values)>-1e-10)
      expect_equal(dimnames(actual$covariance),rep(list(as.character(actual$source_rows)),2))
    } else expect_identical(actual$status,"no_internal_missing")
    if(actual$transformation=="log") {
      expect_equal(actual$standard_errors_original,exp(actual$points_transformed+diag(actual$covariance)/2)*sqrt(expm1(diag(actual$covariance))),check.attributes=FALSE,tolerance=2e-10)
      expect_identical(actual$original_uncertainty_status,"available")
      means <- exp(actual$points_transformed+diag(actual$covariance)/2)
      expect_equal(actual$means_original,means,check.attributes=FALSE,tolerance=2e-10)
      target <- sign(actual$covariance)*exp(outer(log(means),log(means),'+')+log(abs(expm1(actual$covariance))))
      if(all(is.finite(target)) && !any(actual$covariance!=0 & target==0))
        expect_equal(actual$covariance_original,target,check.attributes=FALSE,tolerance=2e-10)
      else expect_identical(actual$original_covariance_status,'original_covariance_range')
    } else expect_identical(actual$standard_errors_original,actual$standard_errors)
  }
  # More than one internal gap, all differencing parities/orders, pure AR/MA,
  # known/fitted regression, initial diffuse holes and transformations.
  for(ca in legacy_residual_cases()) {
    context <- do.call(setup,ca$arguments);actual <- information(context,scale="residual_df")
    target <- interpolation_oracle(context,actual$center$parameters$coefficients)
    expect_true(actual$available,info=ca$id)
    expect_equal(actual$points_transformed,target$points,tolerance=2e-8,info=ca$id)
    expect_equal(unname(actual$known_regression_covariance),target$known*target$Q/actual$residual_df,tolerance=2e-8)
    expect_equal(unname(actual$regression_covariance),target$regression*target$Q/actual$residual_df,tolerance=2e-8)
    expect_equal(unname(actual$covariance),target$covariance*target$Q/actual$residual_df,tolerance=2e-8)
    expect_equal(actual$covariance,actual$known_regression_covariance+actual$regression_covariance,tolerance=1e-12)
  }
  y <- ts(c(NA,1,NA,3,4,NA),frequency=4)
  ar <- information(setup(y,ar=.5))
  expect_equal(ar$points_transformed,1.6,tolerance=1e-12)
  expect_equal(unname(ar$covariance)/ar$scale_variance,matrix(1/1.25,1,1),tolerance=1e-12)
  expect_equal(unname(ar$regression_covariance),matrix(0,1,1),tolerance=0)
  expect_identical(ar$unfilled_rows,c(1L,6L))
  x <- ts(seq_along(y),frequency=4)
  fixed <- information(setup(y+3+2*x,ar=.5,mean=3,regressors=list(x=x),coefficients=c(x=2)))
  expect_equal(fixed$covariance,ar$covariance,tolerance=1e-12)
  expect_equal(fixed$points_transformed,1.6+9,tolerance=1e-12)
  for(multiplier in c(.001,-2,1000)) {
    changed <- information(setup(y*multiplier,ar=.5))
    expect_equal(changed$points_transformed,ar$points_transformed*multiplier,tolerance=1e-10)
    expect_equal(changed$covariance,ar$covariance*multiplier^2,tolerance=1e-10)
    expect_equal(changed$standard_errors,ar$standard_errors*abs(multiplier),tolerance=1e-10)
  }
  logged <- information(setup(exp(y),ar=.5,transformation="log"))
  expect_equal(logged$points_original,exp(1.6),tolerance=1e-12)
  expect_equal(logged$covariance,ar$covariance,tolerance=1e-12)
  expect_true(all(is.finite(logged$standard_errors_original)))
  # A finite transformed prediction can have an unrepresentable inverse point.
  # Preserve its covariance and the observed original values in that case.
  extreme_y <- ts(exp(c(1,NA,2,3,4,2)),frequency=4)
  impulse <- ts(c(0,1,0,0,0,0),frequency=4)
  extreme <- information(setup(extreme_y,transformation="log",regressors=list(x=impulse),coefficients=c(x=1000)))
  expect_true(extreme$available && extreme$point_available)
  expect_equal(extreme$points_transformed,1000,tolerance=1e-12)
  expect_identical(extreme$original_point_status,"original_scale_range")
  expect_true(is.finite(extreme$standard_errors) && is.na(extreme$points_original))
  expect_identical(extreme$original,extreme_y)
  # OLS: each unobserved white-noise value has unit process variance and the
  # same fitted-mean error, so their off-diagonal covariance is sigma2/nobs.
  white <- information(setup(ts(c(1,NA,3,NA,4,5),frequency=4),include_mean=TRUE))
  expect_equal(white$points_transformed,c(3.25,3.25),tolerance=1e-12)
  expect_equal(unname(white$known_regression_covariance),diag(2)*8.75/4,tolerance=1e-12)
  expect_equal(unname(white$regression_covariance),matrix(8.75/16,2,2),tolerance=1e-12)
  # Two points of a same-season random-walk bridge share process error.
  y <- ts(c(7,21,3,13,9,NA,8,16,11,NA,6,18,14,31,12,19),frequency=4)
  bridge <- information(setup(y,seasonal_d=1L))
  expect_equal(bridge$points_transformed,c(21+10/3,21+20/3),tolerance=1e-12)
  expect_equal(unname(bridge$known_regression_covariance)/bridge$scale_variance,matrix(c(2,1,1,2)/3,2,2),tolerance=1e-12)
  legacy <- residuals(setup(y,seasonal_d=1L),reporting="legacy")
  expect_true(max(abs(bridge$points_transformed-legacy$interpolation$points_transformed))>1)
  expect_identical(bridge$points_transformed,legacy$accurate_interpolation$points_transformed)
  # No df does not discard valid Gaussian points or invent zero errors.
  short <- information(setup(ts(c(1,NA,2),frequency=4),ar=rep(NA_real_,2)),scale="residual_df")
  expect_true(short$point_available);expect_false(short$available)
  expect_identical(short$status,"nonpositive_residual_df")
  expect_true(all(is.na(short$standard_errors)) && is.null(short$covariance))
  for(y in list(ts(rep(NA_real_,12),frequency=4),ts(rep(0,12),frequency=4))) {
    bad <- information(setup(y));expect_false(bad$available || bad$point_available)
    expect_identical(bad$original,y);expect_true(is.null(bad$covariance))
  }
  y <- ts(c(1,NA,3,4,2,5),frequency=4);x <- ts(seq_along(y),frequency=4)
  original <- information(setup(y,regressors=list(x=x)))
  for(multiplier in c(1e-6,-3,1e6)) {
    changed <- information(setup(y,regressors=list(x=x*multiplier)))
    expect_equal(changed$covariance,original$covariance,tolerance=1e-10)
    expect_equal(changed$regression_covariance,original$regression_covariance,tolerance=1e-10)
    expect_equal(changed$points_transformed,original$points_transformed,tolerance=1e-10)
  }
  bad <- information(setup(y,regressors=list(x=x,x2=x)))
  expect_false(bad$available);expect_identical(bad$center$status,"rank_deficient")
  for(scale in list(NULL,NA_character_,c("ml","residual_df"),matrix("ml"),"unknown",1))
    expect_error(information(setup(y),scale=scale))
  expect_error(information(list()))
  rejected <- information(setup(y,ar=NA_real_),coordinates=1000)
  expect_false(rejected$available || rejected$point_available)
  expect_true(is.null(rejected$covariance))
  # Orthogonal observed response gives beta=0 and an exactly representable
  # point, while the nonzero variance increment (1e-200)^2 is out of range.
  tiny_x <- ts(c(0,1e-200,1,0,0,0),frequency=4)
  underflow <- information(setup(ts(c(1,NA,0,4,5,6),frequency=4),regressors=list(x=tiny_x)))
  expect_true(underflow$point_available)
  expect_false(underflow$available)
  expect_identical(underflow$status,"numerical_failure")
  expect_true(is.null(underflow$covariance) && all(is.na(underflow$standard_errors)))
  # More than 32 integrated missing coordinates and enough covariance entries
  # to exercise owned OpenMP covariance loops, including a regression increment.
  old <- Sys.getenv("PERSEPHONE_NUM_THREADS",unset=NA_character_)
  on.exit(if(is.na(old))Sys.unsetenv("PERSEPHONE_NUM_THREADS")else Sys.setenv(PERSEPHONE_NUM_THREADS=old),add=TRUE)
  y <- ts(3+sin(seq_len(600)*1.7),frequency=12);y[seq.int(41,560,2)] <- NA_real_
  context <- setup(y,include_mean=TRUE)
  Sys.setenv(PERSEPHONE_NUM_THREADS=1);serial <- information(context)
  Sys.setenv(PERSEPHONE_NUM_THREADS=2);parallel <- information(context)
  expect_true(parallel$available)
  expect_identical(serial$covariance,parallel$covariance)
  expect_identical(serial$regression_covariance,parallel$regression_covariance)
  expect_identical(serial$standard_errors,parallel$standard_errors)
  expect_equal(unname(serial$known_regression_covariance)/serial$scale_variance,diag(260),tolerance=1e-10)
  expect_equal(unname(serial$regression_covariance)/serial$scale_variance,matrix(1/340,260,260),tolerance=1e-10)
})
