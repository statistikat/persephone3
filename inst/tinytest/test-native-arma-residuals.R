local({
  setup <- getFromNamespace("native_arma_objective_setup","persephone3")
  optimize <- getFromNamespace("native_arma_optimize","persephone3")
  residuals <- getFromNamespace("native_arma_residuals","persephone3")
  source("fixtures/native/arma-fit-cases.R",local=TRUE)
  source("fixtures/native/arma-residual-oracle.R",local=TRUE)
  source("fixtures/native/innovation-oracle.R",local=TRUE)
  cases <- arma_fit_cases()
  for(ca in cases) {
    context <- do.call(setup,ca$arguments)
    fit <- optimize(context,control=list(max_iterations=200L,max_evaluations=4000L))
    before <- serialize(context,NULL)
    result <- residuals(context,fit$coordinates)
    oracle <- arma_residual_basis(ca,fit$final$parameters$coefficients)
    rows <- tail(oracle$rows,length(oracle$residuals))
    local_rows <- match(rows,ca$rows)
    n <- oracle$finite;k <- sum(is.na(unlist(ca$specification)));Q <- sum(oracle$residuals^2)
    expect_identical(result$status,"available",info=ca$id)
    expect_true(result$available && result$complete$available && result$interpolation$available)
    expect_identical(result$scale,"ml")
    expect_false(result$studentized || result$propagates_parameter_uncertainty)
    expect_equal(result$effective_count,n,tolerance=0)
    expect_equal(result$residual_df,n-2L-k,tolerance=0)
    expect_equal(result$scale_variance,Q/n,tolerance=1e-9)
    expect_identical(result$span$source_rows,ca$rows)
    expect_identical(result$complete$source_rows,rows)
    expect_equal(as.numeric(result$complete$unit_residuals[local_rows]),oracle$residuals,tolerance=1e-8,info=ca$id)
    expect_equal(as.numeric(result$complete$scaled_residuals[local_rows]),oracle$residuals/sqrt(Q/n),tolerance=1e-8)
    expect_true(all(is.na(result$complete$unit_residuals[-local_rows])))
    expect_equal(result$complete$sum_squares,Q,tolerance=1e-9)
    expect_equal(sum(result$observed$unit_innovations^2,na.rm=TRUE),Q,tolerance=1e-8)
    expect_equal(sum(result$observed$standardized_innovations^2,na.rm=TRUE),n,tolerance=1e-8)
    expect_true(all(is.na(result$observed$standardized_innovations[context$prepared$inputs$missing])))
    expect_identical(which(result$observed$row_kind=="finite"),result$observed$rows)
    expect_equal(length(result$observed$rows),n,tolerance=0)
    expect_identical(result$observed$source_rows,ca$rows[result$observed$rows])
    expect_identical(tsp(result$observed$standardized_innovations),tsp(context$prepared$inputs$original))
    expect_equal(result$interpolation$points_transformed,oracle$interpolated,tolerance=1e-9)
    expect_identical(result$interpolation$source_rows,oracle$rows[oracle$missing])
    points <- if(ca$arguments$transformation=="log")exp(oracle$interpolated)else oracle$interpolated
    expect_equal(result$interpolation$points_original,points,tolerance=1e-9)
    present <- !context$prepared$inputs$missing
    expect_identical(result$interpolation$original[present],context$prepared$inputs$original[present])
    expect_identical(result$interpolation$transformed[present],context$prepared$inputs$transformed[present])
    expect_true(all(is.na(result$interpolation$standard_errors)))
    expect_identical(result$interpolation$mean_adjustment,"none")
    expect_identical(serialize(context,NULL),before)
    expect_identical(unserialize(serialize(result,NULL)),result)
    df <- residuals(context,fit$coordinates,scale="residual_df")
    expect_identical(df$status,"available")
    expect_identical(df$observed$unit_innovations,result$observed$unit_innovations)
    expect_equal(df$scale_variance,Q/(n-2L-k),tolerance=1e-9)
    expect_equal(sum(df$observed$standardized_innovations^2,na.rm=TRUE),n-2L-k,tolerance=1e-8)
    expect_equal(df$complete$scaled_residuals,result$complete$scaled_residuals*sqrt((n-2L-k)/n),tolerance=1e-10)
    expect_identical(df$interpolation,result$interpolation)
    # Log cases have the same transformed Gaussian model; the separate 32
    # non-log cases qualify chronological finite innovations independently.
    if(ca$arguments$transformation=="none") {
      beta <- c(oracle$coefficients[1L],.2,oracle$coefficients[2L])
      gaussian <- innovation_oracle(ca,fit$final$parameters$coefficients,beta)
      expect_identical(result$observed$row_kind,gaussian$kind,info=ca$id)
      expect_true(all(abs(as.numeric(result$observed$unit_innovations)-gaussian$unit)<2e-7*(1+abs(gaussian$unit)),na.rm=TRUE),info=ca$id)
    }
  }
  # Closed stationary AR(1) conditioning across a gap, with trimmed endpoint
  # holes retained as unavailable original-domain values.
  y <- ts(c(NA,1,NA,3,4,NA),frequency=4)
  result <- residuals(setup(y,ar=.5))
  expected <- c(sqrt(.75),(3-.25)/sqrt(1.25),4-.5*3)
  expect_equal(as.numeric(result$observed$unit_innovations[c(2,4,5)]),expected,tolerance=1e-12)
  expect_equal(result$interpolation$points_transformed,1.6,tolerance=1e-12)
  expect_identical(result$interpolation$rows,3L)
  expect_identical(result$interpolation$unfilled_rows,c(1L,6L))
  expect_identical(result$complete$rows,2:5)
  expect_identical(result$complete$rows_were_missing,c(FALSE,TRUE,FALSE,FALSE))
  expect_equal(sum(result$complete$unit_residuals^2,na.rm=TRUE),sum(expected^2),tolerance=1e-12)
  expect_true(abs(result$observed$unit_innovations[4]-result$complete$unit_residuals[4])>.1)
  # Known mean and fixed regression effects are restored in interpolation.
  x <- ts(seq_along(y),frequency=4)
  changed <- residuals(setup(y+3+2*x,ar=.5,mean=3,regressors=list(x=x),coefficients=c(x=2)))
  expect_equal(changed$observed$unit_innovations,result$observed$unit_innovations,tolerance=1e-12)
  expect_equal(changed$interpolation$points_original,1.6+3+2*3,tolerance=1e-12)
  logged <- residuals(setup(exp(y),ar=.5,transformation="log"))
  expect_equal(logged$interpolation$points_original,exp(1.6),tolerance=1e-12)
  expect_identical(logged$interpolation$point_convention,"exponentiated_transformed_point")
  # A seasonal random walk conditions on the same season on either side.
  # This closed case deliberately distinguishes it from adjacent-time filling.
  seasonal <- ts(c(7,21,3,13,9,NA,8,16,11,27,6,18,14,31,12,19),frequency=4)
  seasonal_result <- residuals(setup(seasonal,seasonal_d=1L))
  expect_equal(seasonal_result$interpolation$points_original,(21+27)/2,tolerance=1e-12)
  expect_equal(seasonal_result$sum_squares,130,tolerance=1e-12)
  expect_equal(seasonal_result$complete$sum_squares,130,tolerance=1e-12)
  expect_identical(seasonal_result$interpolation$rows,6L)
  for(scale in c(.001,7,-2)) {
    changed <- residuals(setup(y*scale,ar=.5))
    expect_equal(changed$observed$standardized_innovations,result$observed$standardized_innovations*sign(scale),tolerance=1e-12)
    expect_equal(changed$interpolation$points_transformed,result$interpolation$points_transformed*scale,tolerance=1e-12)
  }
  for(value in list(ts(rep(NA_real_,12),frequency=4),ts(rep(0,12),frequency=4))) {
    unavailable <- residuals(setup(value))
    expect_false(unavailable$available || unavailable$complete$available || unavailable$interpolation$available)
    expect_true(all(is.na(unavailable$observed$standardized_innovations)))
    expect_identical(unavailable$interpolation$original,value)
    expect_identical(unavailable$interpolation$uncertainty_status,"point_unavailable")
  }
  y <- ts(c(.2,.6,-.3,.1,-.7,-.3,.1,.7,.6,-.2,-.5,.3),frequency=4)
  alias <- residuals(setup(y,regressors=list(x=y,x2=y)))
  expect_false(alias$available)
  expect_identical(alias$center$status,"rank_deficient")
  unavailable <- residuals(setup(y,ar=NA_real_),1000)
  expect_false(unavailable$available)
  expect_true(all(is.na(unavailable$observed$unit_innovations)))
  # This is a point diagnostic, so available residuals do not imply a qualified
  # optimizer optimum or identified ARMA covariance.
  context <- setup(y,ar=NA_real_)
  expect_true(residuals(context)$available)
  common <- setup(y,ar=NA_real_,ma=NA_real_,initial=list(ar=.3,ma=-.3))
  expect_true(residuals(common)$available)
  short <- setup(ts(c(1,2),frequency=4),ar=rep(NA_real_,2))
  expect_true(residuals(short)$available)
  no_df <- residuals(short,scale="residual_df")
  expect_identical(no_df$status,"nonpositive_residual_df")
  expect_false(no_df$available)
  expect_true(all(is.na(no_df$observed$standardized_innovations)))
  for(scale in list(NULL,NA_character_,c("ml","residual_df"),matrix("ml"),"unknown",1)) {
    expect_error(residuals(context,scale=scale))
  }
  # Parallel scaling uses independent outputs; whitening remains conditional
  # and ordered within each channel. The large white-noise case crosses the
  # shared OpenMP work threshold without any large dense covariance matrix.
  old <- Sys.getenv("PERSEPHONE_NUM_THREADS",unset=NA_character_)
  on.exit(if(is.na(old))Sys.unsetenv("PERSEPHONE_NUM_THREADS")else Sys.setenv(PERSEPHONE_NUM_THREADS=old),add=TRUE)
  context <- setup(ts(sin(seq_len(70000)*1.7),start=c(2000,1),frequency=12))
  Sys.setenv(PERSEPHONE_NUM_THREADS=1);serial <- residuals(context)
  Sys.setenv(PERSEPHONE_NUM_THREADS=2);threaded <- residuals(context)
  expect_true(threaded$available && threaded$complete$available)
  expect_identical(serial$observed$standardized_innovations,threaded$observed$standardized_innovations)
  expect_identical(serial$complete$scaled_residuals,threaded$complete$scaled_residuals)
})
