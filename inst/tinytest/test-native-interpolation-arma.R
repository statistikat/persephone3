local({
  setup <- getFromNamespace("native_arma_objective_setup","persephone3")
  optimize <- getFromNamespace("native_arma_optimize","persephone3")
  information <- getFromNamespace("native_interpolation_information","persephone3")
  arma_information <- getFromNamespace("native_arma_information","persephone3")
  propagated <- function(context,coordinates=context$parameters$initial_coordinates,...)
    information(context,coordinates,method="delta_profile_ml",...)
  source("fixtures/native/arma-fit-cases.R",local=TRUE)
  source("fixtures/native/arma-residual-oracle.R",local=TRUE)
  source("fixtures/native/interpolation-oracle.R",local=TRUE)
  source("fixtures/native/interpolation-arma-oracle.R",local=TRUE)
  source("fixtures/native/joint-information-oracle.R",local=TRUE)
  relative <- function(a,b)sqrt(sum((a-b)^2)/sum(b^2))
  cases <- arma_fit_cases()
  for(ca in cases) {
    context <- do.call(setup,ca$arguments)
    fit <- optimize(context,control=list(max_iterations=200L,max_evaluations=4000L))
    before <- serialize(context,NULL)
    conditional <- information(context,fit$coordinates)
    actual <- propagated(context,fit$coordinates)
    expect_true(actual$available && actual$conditional_available && actual$point_available,info=ca$id)
    expect_identical(actual$conditional_covariance,conditional$covariance)
    expect_identical(actual$conditional_standard_errors,conditional$standard_errors)
    expect_identical(actual$points_transformed,conditional$points_transformed)
    expect_identical(actual$known_regression_covariance,conditional$known_regression_covariance)
    expect_identical(actual$regression_covariance,conditional$regression_covariance)
    expect_identical(actual$center,conditional$center)
    expect_identical(actual$method,"delta_profile_ml")
    expect_true(actual$propagates_ARMA_uncertainty && !actual$comparison_only)
    expect_identical(serialize(context,NULL),before)
    expect_identical(unserialize(serialize(actual,NULL)),actual)
    expect_identical(actual$rows,conditional$rows)
    expect_identical(actual$unfilled_rows,conditional$unfilled_rows)
    if(!length(actual$rows)) {
      expect_identical(actual$status,"no_internal_missing")
      expect_identical(actual$sensitivity_status,"not_required")
      expect_identical(actual$evaluations,0L)
      expect_identical(dim(actual$sensitivity),c(0L,actual$free_ARMA))
      next
    }
    expect_identical(actual$status,"available",info=ca$id)
    expect_identical(actual$arma_information_status,"available")
    expect_identical(actual$arma_information$method,"profile_ml")
    expect_identical(actual$arma_information$covariance_mode,"accurate")
    expect_identical(actual$sensitivity_status,"available")
    expect_true(actual$evaluations==actual$arma_information$evaluations+actual$sensitivity_evaluations)
    expect_true(actual$evaluations<=actual$evaluation_budget)
    expect_true(all(is.finite(actual$sensitivity_error)) && all(actual$sensitivity_error>=0))
    expect_identical(rownames(actual$sensitivity),as.character(actual$source_rows))
    expect_identical(colnames(actual$sensitivity),names(actual$arma_coefficients))
    target <- interpolation_arma_sensitivity(context,fit$final$parameters$coefficients)
    expect_true(all(abs(actual$sensitivity-target$sensitivity)<2e-7*(1+abs(target$sensitivity))),info=ca$id)
    expect_equal(unname(actual$arma_increment),unname(actual$sensitivity%*%actual$arma_parameter_covariance%*%t(actual$sensitivity)),tolerance=1e-10)
    expect_equal(actual$covariance,actual$conditional_covariance+actual$arma_increment,tolerance=1e-12)
    expect_equal(actual$standard_errors,sqrt(diag(actual$covariance)),tolerance=1e-12,check.attributes=FALSE)
    expect_true(all(actual$standard_errors>=actual$conditional_standard_errors))
    expect_true(min(eigen(actual$arma_increment,symmetric=TRUE,only.values=TRUE)$values)>-1e-12)
    expect_identical(actual$covariance,t(actual$covariance))
    # The independent full Gaussian Hessian supplies a separate ARMA covariance
    # target; public preprocessors do not propagate this uncertainty.
    basis <- arma_residual_basis(ca,fit$final$parameters$coefficients)
    C <- basis$regression_covariance_unit*sum(basis$residuals^2)/basis$finite
    joint <- joint_information_oracle(ca,fit$final$parameters$coefficients,basis$coefficients,
      sqrt(diag(C)),sqrt(diag(actual$arma_parameter_covariance)))
    ix <- 2L+seq_len(actual$free_ARMA)
    Vtheta <- joint$scaled_covariance[ix,ix,drop=FALSE]*outer(joint$scale[ix],joint$scale[ix])
    independent <- interpolation_oracle(context,fit$final$parameters$coefficients)
    expected <- independent$covariance*independent$Q/independent$n+target$sensitivity%*%Vtheta%*%t(target$sensitivity)
    units <- outer(conditional$standard_errors,conditional$standard_errors)
    expect_true(relative(actual$covariance/units,expected/units)<2e-5,info=ca$id)
  }
  ca <- cases[["4-ar-gaps-none"]];context <- do.call(setup,ca$arguments)
  fit <- optimize(context);base <- propagated(context,fit$coordinates)
  primary <- arma_information(context,fit$coordinates)
  for(budget in c(1L,primary$evaluations,primary$evaluations+1L,base$evaluations-1L)) {
    limited <- propagated(context,fit$coordinates,control=list(max_evaluations=budget))
    expect_false(limited$available)
    expect_true(limited$conditional_available && limited$point_available)
    expect_identical(limited$conditional_covariance,base$conditional_covariance)
    expect_identical(limited$points_transformed,base$points_transformed)
    expect_true(is.null(limited$covariance) && is.null(limited$arma_increment))
    expect_true(all(is.na(limited$standard_errors)) && length(limited$standard_errors)==length(limited$rows))
    expect_true(limited$evaluations<=budget)
    if(budget>=primary$evaluations)expect_identical(limited$status,"evaluation_limit")
  }
  expect_true(propagated(context,fit$coordinates,control=list(max_evaluations=base$evaluations))$available)
  for(multiplier in c(.001,-2,1000)) {
    args <- ca$arguments;args$series <- args$series*multiplier;args$regressors$fixed <- args$regressors$fixed*multiplier
    changed <- propagated(do.call(setup,args),fit$coordinates)
    expect_true(changed$available)
    expect_true(relative(changed$covariance,base$covariance*multiplier^2)<1e-6)
    expect_true(relative(changed$sensitivity,base$sensitivity*multiplier)<1e-6)
  }
  args <- ca$arguments;args$series <- args$series+1000*head(args$regressors$x,length(args$series))
  shifted <- propagated(do.call(setup,args),fit$coordinates)
  expect_true(shifted$available)
  expect_true(relative(shifted$covariance,base$covariance)<1e-6)
  expect_true(relative(shifted$sensitivity,base$sensitivity)<1e-6)
  args <- ca$arguments;args$regressors$x <- args$regressors$x*1e3
  changed <- propagated(do.call(setup,args),fit$coordinates)
  expect_true(changed$available)
  expect_true(relative(changed$covariance,base$covariance)<1e-6)
  for(point in list(context$parameters$initial_coordinates,1000)) {
    unavailable <- propagated(context,point)
    expect_false(unavailable$available)
    expect_true(is.null(unavailable$covariance) && all(is.na(unavailable$standard_errors)))
  }
  y <- ts(c(.2,.6,-.3,.1,-.7,NA,.1,.7,.6,-.2,-.5,.3),frequency=4)
  fixed <- propagated(setup(y,ar=.3,include_mean=TRUE))
  expect_true(fixed$available)
  expect_identical(fixed$sensitivity_status,"not_required")
  expect_identical(fixed$covariance,fixed$conditional_covariance)
  expect_identical(dim(fixed$sensitivity),c(1L,0L))
  expect_true(all(fixed$arma_increment==0))
  common <- propagated(setup(y,ar=NA_real_,ma=NA_real_,initial=list(ar=.3,ma=-.3),include_mean=TRUE))
  expect_false(common$available)
  expect_true(common$conditional_available)
  expect_identical(common$arma_information_status,"structural_redundancy")
  weak_context <- do.call(setup,cases[["4-arma-gaps-none"]]$arguments)
  weak_fit <- optimize(weak_context)
  weak <- propagated(weak_context,weak_fit$coordinates,control=list(weak_tolerance=.99))
  expect_false(weak$available)
  expect_true(weak$conditional_available)
  for(method in list(NULL,NA_character_,c("conditional","delta_profile_ml"),matrix("conditional"),"legacy",1))
    expect_error(information(context,method=method))
  expect_error(propagated(context,fit$coordinates,scale="residual_df"))
  expect_error(information(context,control=list(max_evaluations=1L)))
  expect_error(propagated(context,control=list(unrecognised=1L)))
  expect_error(propagated(context,control=1))
  tiny <- propagated(setup(ts(c(1,NA,0,4,5,6),frequency=4),ar=NA_real_,
    regressors=list(x=ts(c(0,1e-200,1,0,0,0),frequency=4))))
  expect_false(tiny$available || tiny$conditional_available)
  expect_true(tiny$point_available)
  expect_identical(tiny$status,"conditional_unavailable")
  expect_true(length(tiny$standard_errors)==length(tiny$rows) && all(is.na(tiny$standard_errors)))
  # Closed AR(1) formulas check the whole point sensitivity, including the
  # effect of re-estimating a mean at each parameter perturbation.
  seed <- if(exists(".Random.seed",.GlobalEnv))get(".Random.seed",.GlobalEnv)else NULL
  set.seed(1042);noise <- rnorm(240)
  for(phi in c(-.8,.4,.97))for(mean in c(FALSE,TRUE)) {
    y <- ts(as.numeric(filter(noise,phi,method="recursive")),frequency=4);y[100] <- NA_real_
    context <- setup(y,ar=NA_real_,include_mean=mean)
    f <- optimize(context,control=list(max_iterations=200L,max_evaluations=4000L))
    actual <- propagated(context,f$coordinates)
    expect_true(actual$available)
    expected <- ar1_interpolation_sensitivity(y,unname(actual$arma_coefficients),mean)
    expect_equal(as.numeric(actual$sensitivity),expected,tolerance=2e-7)
  }
  y <- ts(noise,frequency=4);y[99] <- 1;y[100] <- NA_real_;y[101] <- -1
  context <- setup(y,ar=NA_real_);f <- optimize(context);zero <- propagated(context,f$coordinates)
  expect_true(zero$available)
  expect_equal(as.numeric(zero$sensitivity),0,tolerance=1e-9)
  expect_equal(zero$covariance,zero$conditional_covariance,tolerance=1e-12)
  if(is.null(seed))rm(".Random.seed",envir=.GlobalEnv)else assign(".Random.seed",seed,.GlobalEnv)
  # Integrated homogeneous offsets change levels, not point sensitivities.
  ca <- cases[["4-seasonal_ar-gaps-none"]];context <- do.call(setup,ca$arguments);f <- optimize(context)
  base <- propagated(context,f$coordinates)
  args <- ca$arguments;args$series <- args$series+rep(c(10,-20,30,-40),length.out=length(args$series))
  shifted <- propagated(do.call(setup,args),f$coordinates)
  expect_true(shifted$available)
  expect_true(relative(shifted$covariance,base$covariance)<1e-6)
  expect_true(relative(shifted$sensitivity,base$sensitivity)<1e-6)
  old <- Sys.getenv("PERSEPHONE_NUM_THREADS",unset=NA_character_)
  on.exit(if(is.na(old))Sys.unsetenv("PERSEPHONE_NUM_THREADS")else Sys.setenv(PERSEPHONE_NUM_THREADS=old),add=TRUE)
  ca <- cases[["12-airline-gaps-log"]];context <- do.call(setup,ca$arguments);f <- optimize(context)
  Sys.setenv(PERSEPHONE_NUM_THREADS=1);serial <- propagated(context,f$coordinates)
  Sys.setenv(PERSEPHONE_NUM_THREADS=2);parallel <- propagated(context,f$coordinates)
  expect_true(serial$available && parallel$available)
  expect_equal(serial$covariance,parallel$covariance,tolerance=1e-10)
  expect_true(all(abs(serial$sensitivity-parallel$sensitivity)<=serial$sensitivity_error+parallel$sensitivity_error))
  # Alternating support makes the AR(1) score exactly zero at phi=0; successive
  # nonzero values have opposite signs, giving positive local curvature. Varying
  # their amplitudes gives nonzero missing-point sensitivities. The 260x260
  # ARMA covariance increment crosses the actual OpenMP work threshold.
  t <- seq_len(600);y <- numeric(600);even <- t%%2L==0L
  y[even] <- (-1)^(t[even]/2)*(1+.1*(t[even]%%7L));y[seq.int(41,560,2)] <- NA_real_
  context <- setup(ts(y,frequency=12),ar=NA_real_)
  Sys.setenv(PERSEPHONE_NUM_THREADS=1);serial <- propagated(context)
  Sys.setenv(PERSEPHONE_NUM_THREADS=2);parallel <- propagated(context)
  expect_true(serial$available && parallel$available)
  expect_equal(serial$covariance,parallel$covariance,tolerance=1e-10)
  expect_equal(serial$arma_increment,parallel$arma_increment,tolerance=1e-10)
  expect_equal(as.numeric(serial$sensitivity),y[serial$rows-1L]+y[serial$rows+1L],tolerance=2e-7)
})
