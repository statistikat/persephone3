# Numerical foundations only: these tests do not claim native model fitting.
domain <- getFromNamespace(".native_time_domain", "persephone3")
poly <- getFromNamespace(".native_difference_polynomial", "persephone3")
convolve <- getFromNamespace(".native_convolve", "persephone3")
filter <- getFromNamespace(".native_filter", "persephone3")

monthly <- domain(2020, 11, 12, 4)
expect_equal(monthly$start, c(2020, 11))
expect_equal(monthly$end, c(2021, 2))
expect_equal(monthly[["next"]], c(2021, 3))
expect_equal(monthly$frequency, 12L)
expect_equal(monthly$length, 4)
quarterly <- domain(2020, 4, 4, 6)
expect_equal(quarterly$end, c(2022, 1))
expect_equal(quarterly[["next"]], c(2022, 2))
expect_equal(domain(-1, 4, 4, 2)$end, c(0, 1))
expect_equal(domain(2020, 1, 12, 0)$end, NULL)
expect_equal(domain(2020, 1, 12, 0)[["next"]], c(2020, 1))
expect_error(domain(2020, 1, 1, 12), "frequency")
expect_error(domain(2020, 5, 4, 12), "start period")
expect_error(domain(2020.5, 1, 12, 12), "integer")
expect_error(domain(2020, 1, 12, -1), "nonnegative")
expect_error(domain(2020, 1, 12, Inf), "finite")
expect_error(domain(1e15, 1, 12, 12), "exact integer range")

# Hand-computed coefficients, not generated using the native implementation.
expect_equal(poly(0, 0, 12), 1)
expect_equal(poly(2, 0, 12), c(1, -2, 1))
expect_equal(poly(1, 1, 4), c(1, -1, 0, 0, -1, 1))
expect_equal(poly(0, 2, 4), c(1, 0, 0, 0, -2, 0, 0, 0, 1))
expect_equal(poly(1, 1, 12), c(1, -1, rep(0, 10), -1, 1))
expect_error(poly(-1, 0, 12), "between 0 and 64")
expect_error(poly(0.5, 0, 12), "integer")
expect_error(poly(65, 0, 12), "between 0 and 64")
expect_error(poly(1, 1, 52), "frequency")
expect_equal(convolve(c(1, 2), c(3, 4)), c(3, 10, 8))
expect_equal(convolve(c(0, 1), c(3, 4)), c(0, 3, 4))
expect_equal(convolve(2, c(1, -2)), c(2, -4))
expect_error(convolve(numeric(), 1), "at least one")
expect_error(convolve(c(1, NA_real_), 1), "finite")
expect_error(convolve(1e308, 10), "non-finite")

# Compare finite filtering against independent R operations on original indices.
x <- c(4, 7, 2, 10, 6, 12, 11, 15, 20, 17, 25, 28)
regular <- filter(x, c(1, -1), c(0, -1))
expect_equal(regular$values, c(NA_real_, diff(x)))
expect_equal(regular$missing, c(TRUE, rep(FALSE, length(x) - 1)))
seasonal <- filter(x, poly(1, 1, 4), -(0:5))
expect_equal(seasonal$values, c(rep(NA_real_, 5), diff(diff(x, lag = 4))))
centered <- filter(x, c(1, 2, 1) / 4, c(-1, 0, 1))
expect_equal(centered$values, as.numeric(stats::filter(x, c(1, 2, 1) / 4)))
expect_equal(filter(x, 1, 1)$values, c(x[-1], NA_real_))
expect_equal(filter(x, 1, -100)$missing, rep(TRUE, length(x)))
expect_equal(filter(x, 1, 100)$missing, rep(TRUE, length(x)))
expect_equal(filter(numeric(), 1, 0), list(values = numeric(), missing = logical()))

# Missingness follows only active taps, with NA/NaN both representing missing.
incomplete <- c(1, NA_real_, 3, NaN, 5)
identity <- filter(incomplete, c(1, 0), c(0, -1000))
expect_equal(identity$values, c(1, NA_real_, 3, NA_real_, 5))
expect_equal(identity$missing, c(FALSE, TRUE, FALSE, TRUE, FALSE))
expect_equal(filter(incomplete, 0, 999)$values, rep(0, 5))
expect_equal(filter(incomplete, 0, 999)$missing, rep(FALSE, 5))
expect_equal(filter(incomplete, c(1, -1), c(0, -1))$missing, rep(TRUE, 5))
expect_equal(filter(c(1e308, NA_real_), c(10, 1), c(0, 1))$missing, c(TRUE, TRUE))
expect_equal(filter(c(1e308, NA_real_), c(1, 10), c(1, 0))$missing, c(TRUE, TRUE))

expect_error(filter(1:3, c(1, 1), 0), "equal nonzero lengths")
expect_error(filter(1:3, numeric(), numeric()), "equal nonzero lengths")
expect_error(filter(1:3, c(1, 1), c(0, 0)), "unique")
expect_error(filter(1:3, NA_real_, 0), "finite")
expect_error(filter(c(1, Inf), 1, 0), "infinity")
expect_error(filter(c(1, -Inf), 1, 0), "infinity")
expect_error(filter(1:3, 1, 0.5), "integer")
expect_error(filter(1:3, 1, NA_real_), "integer")
expect_error(filter(1e308, 10, 0), "non-finite")

# An exception must not mutate input or leave state affecting a later call.
original <- x
expect_error(filter(x, 1, NaN), "integer")
expect_equal(x, original)
expect_equal(filter(x, c(1, -1), c(0, -1)), regular)
