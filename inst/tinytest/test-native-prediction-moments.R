local({
  moments <- getFromNamespace('native_prediction_moments','persephone3')
  setup <- getFromNamespace('native_arma_objective_setup','persephone3')
  interpolate <- getFromNamespace('native_interpolation_information','persephone3')
  forecast <- getFromNamespace('native_arma_forecasts','persephone3')
  m <- c(1,2,-.3);V <- matrix(c(.2,-.05,.03,-.05,.3,-.01,.03,-.01,.1),3)
  dimnames(V) <- rep(list(c('a','b','c')),2)
  for(transform in c('none','log')) {
    actual <- moments(m,V,transform)
    target_mean <- if(transform=='none')m else exp(m+diag(V)/2)
    target <- if(transform=='none')V else outer(target_mean,target_mean)*expm1(V)
    expect_true(actual$available)
    expect_equal(unname(actual$medians),if(transform=='none')m else exp(m),tolerance=1e-13)
    expect_equal(unname(actual$means),target_mean,tolerance=1e-13,check.attributes=FALSE)
    expect_equal(actual$covariance,target,tolerance=1e-13)
    expect_equal(actual$standard_errors,sqrt(diag(target)),tolerance=1e-13)
    expect_identical(actual$covariance,t(actual$covariance))
    expect_true(min(eigen(actual$covariance,symmetric=TRUE,only.values=TRUE)$values)>0)
    expect_true(actual$covariance[1,2]<0 && actual$covariance[1,3]>0)
    expect_identical(unserialize(serialize(actual,NULL)),actual)
  }
  # Stable evaluation avoids exp(V) overflow and permits finite moments even
  # when inverse-point medians are below the representable positive range.
  extreme <- moments(c(-1000,-1000),matrix(c(1000,500,500,1000),2),'log')
  expect_true(extreme$available)
  expect_identical(extreme$median_status,'original_median_range')
  expect_equal(extreme$means/exp(-500),c(1,1),tolerance=1e-13)
  expect_equal(diag(extreme$covariance),c(1,1),tolerance=1e-13)
  expect_equal(extreme$covariance[1,2]/exp(-500),1,tolerance=1e-13)
  # expm1 retains tiny covariance; a negative cross covariance keeps its sign.
  for(cross in c(-1e-200,0,1e-200)) {
    actual <- moments(c(0,0),matrix(c(1e-100,cross,cross,1e-100),2),'log')
    expect_true(actual$available)
    if(cross==0)expect_identical(actual$covariance[1,2],0)else
      expect_equal(actual$covariance[1,2]/cross,1,tolerance=1e-12)
    expect_equal(diag(actual$covariance)/1e-100,c(1,1),tolerance=1e-12)
  }
  # Errors in individual moment ranges preserve the other certified outputs.
  large <- moments(500,matrix(1,1),'log')
  expect_identical(large$mean_status,'available')
  expect_identical(large$covariance_status,'original_covariance_range')
  expect_true(is.null(large$covariance) && is.finite(large$standard_errors))
  expect_identical(large$standard_error_status,'available')
  expect_equal(large$standard_errors/exp(500.5)/sqrt(expm1(1)),1,tolerance=1e-13)
  expect_equal(large$medians,exp(500),tolerance=1e-13)
  small <- moments(-500,matrix(1,1),'log')
  expect_identical(small$mean_status,'available')
  expect_identical(small$covariance_status,'original_covariance_range')
  expect_true(is.null(small$covariance))
  huge <- moments(1000,matrix(1,1),'log')
  expect_identical(huge$median_status,'original_median_range')
  expect_identical(huge$mean_status,'original_mean_range')
  empty <- moments(numeric(),matrix(numeric(),0,0),'log')
  expect_true(empty$available);expect_equal(dim(empty$covariance),c(0L,0L))
  for(bad in list(matrix(c(1,2,2,1),2),matrix(c(1,0,.1,1),2),diag(c(0,1)),diag(c(NA,1)),diag(c(Inf,1))))
    expect_error(moments(c(0,0),bad,'log'))
  for(bad in list(NA_real_,Inf,NaN))expect_error(moments(bad,matrix(1,1),'log'))
  expect_error(moments(c(1,2),matrix(1,1),'log'))
  expect_error(moments(matrix(1),matrix(1),'log'))
  expect_error(moments(1,matrix(1),'unknown'))
  # Model identity mapping retains an already qualified kernel covariance even
  # if its small process diagonal was rounded below the shared component.
  trusted <- getFromNamespace('native_model_prediction_moments','persephone3')(
    c(0,0),matrix(1e16,2,2),'none')
  expect_true(trusted$available)
  expect_identical(trusted$covariance,matrix(1e16,2,2))
  expect_equal(trusted$standard_errors,c(1e8,1e8),tolerance=0)
  # Model integration: original means and covariance are separate from median
  # points; a shorter reported error horizon does not shorten the full matrix.
  y <- ts(exp(c(1,3,2,4,5,2,3,5,4,2,3,6,2,4,5,3)/10),start=2000,frequency=4)
  result <- forecast(setup(y,d=1L,include_drift=TRUE,forecast_horizon=4L,backcast_horizon=3L,transformation='log'),
    forecast_error_horizon=2L,backcast_error_horizon=1L)
  location <- unname(unlist(lapply(result$points_transformed,as.numeric)))
  mean <- exp(location+diag(result$covariance)/2)
  target <- outer(mean,mean)*expm1(result$covariance)
  expect_true(result$original_moments$available)
  expect_equal(unname(unlist(lapply(result$means_original,as.numeric))),unname(mean),tolerance=1e-12)
  expect_equal(result$covariance_original,target,tolerance=1e-12)
  expect_equal(unname(unlist(lapply(result$standard_errors_original,as.numeric))),sqrt(diag(target))[c(3,4,5)],check.attributes=FALSE,tolerance=1e-12)
  expect_identical(result$forecasts$points$y,result$points_original$forecast)
  expect_identical(result$forecasts$standard_errors$y,result$standard_errors_original$forecast)
  expect_identical(result$forecasts$uncertainty_distribution,'lognormal')
  expect_identical(result$forecasts$interval_convention,'exponentiate_Gaussian_quantiles')
  expect_true(all(result$covariance_original[1:3,4:7]<0))
  y[c(5,8)] <- NA_real_
  result <- interpolate(setup(y,ar=.5,transformation='log'))
  expect_equal(result$means_original,exp(result$points_transformed+diag(result$covariance)/2),check.attributes=FALSE,tolerance=1e-12)
  expect_equal(result$standard_errors_original,sqrt(diag(result$covariance_original)),check.attributes=FALSE,tolerance=1e-12)
  expect_equal(result$points_original,exp(result$points_transformed),tolerance=1e-12)
  # Range failure in original moments must never remove transformed results.
  x <- ts(c(rep(0,16),1000,1000),start=2000,frequency=4)
  result <- forecast(setup(y,regressors=list(x=x),coefficients=c(x=1),forecast_horizon=2L,transformation='log'))
  expect_true(result$available && result$point_available)
  expect_identical(result$original_mean_status,'original_mean_range')
  expect_identical(result$original_uncertainty_status,'original_standard_error_range')
  expect_true(all(is.finite(result$standard_errors$forecast)))
  expect_true(all(is.na(result$standard_errors_original$forecast)))
  expect_true(is.null(result$covariance_original))
  # The covariance loop crosses the actual OpenMP threshold.
  old <- Sys.getenv('PERSEPHONE_NUM_THREADS',unset=NA_character_)
  on.exit(if(is.na(old))Sys.unsetenv('PERSEPHONE_NUM_THREADS')else Sys.setenv(PERSEPHONE_NUM_THREADS=old),add=TRUE)
  V <- diag(260)*.1+matrix(.01,260,260);m <- sin(seq_len(260))
  Sys.setenv(PERSEPHONE_NUM_THREADS=1);serial <- moments(m,V,'log')
  Sys.setenv(PERSEPHONE_NUM_THREADS=2);parallel <- moments(m,V,'log')
  expect_true(parallel$available);expect_identical(serial,parallel)
})
